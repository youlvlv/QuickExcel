package com.lizhiwei.quickExcel.entity;

public class ExcelImg {

	/**
	 * noNum
	 */
	String noNum;


	/**
	 * 路径
	 */
	String path;

	/**
	 * 行
	 */
	String row;


	/**
	 * 列
	 */
	String col;


	public String getNoNum() {
		return noNum;
	}

	public void setNoNum(String noNum) {
		this.noNum = noNum;
	}

	public String getPath() {
		return path;
	}

	public void setPath(String path) {
		this.path = path;
	}

	public String getRow() {
		return row;
	}

	public void setRow(String row) {
		this.row = row;
	}

	public String getCol() {
		return col;
	}

	public void setCol(String col) {
		this.col = col;
	}
}
